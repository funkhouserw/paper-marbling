// Copies the current interface's controls into src/fixtures/controls.json, so the mockup shows
// every real tool, setting and simulator without importing the old interface's modules.
// Run again with `npm run fixtures` when tools.js, info.js, models.js or palettes.js change.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { TOOLS, isDial } from '../../tools.js';
import { WEAVE_SHAPES } from '../../engine.js';
import { FONTS } from '../../text.js';
import { INFO } from '../../info.js';
import { MODELS } from '../../models.js';
import { BUILT_IN_PALETTES } from '../../palettes.js';

const tools = Object.fromEntries(Object.entries(TOOLS).map(([id, t]) => [id, {
  label: t.label ?? id[0].toUpperCase() + id.slice(1),
  hint: t.hint,
  whole: Boolean(t.whole),
  color: Boolean(t.color),
  directions: Boolean(t.directions),
  text: Boolean(t.text),
  // Size-like settings show a 0 to 100 dial (further with `over`) instead of page units, as in ui.js.
  params: Object.entries(t.params).map(([key, [label, value, min, max, step, over]]) => ({ key, label, value, min, max, step, dial: isDial(key), ...(over && { over }) })),
  choices: Object.entries(t.choices ?? {}).map(([key, [label, options, value]]) => ({ key, label, options, value })),
}]));

// The example scripts are in examples.js once the tank controller lands. Before that they're
// inside ui.js, which needs a page, so they're read out of its text.
async function loadExamples() {
  try {
    return (await import('../../examples.js')).EXAMPLES;
  } catch (err) {
    if (err.code !== 'ERR_MODULE_NOT_FOUND') throw err;
  }
  const ui = await readFile(new URL('../../ui.js', import.meta.url), 'utf8');
  const block = ui.match(/\nconst EXAMPLES = (\{[\s\S]*?\n\});/);
  if (!block) throw new Error('No EXAMPLES in examples.js or ui.js');
  return new Function(`return ${block[1]}`)();
}
const examples = await loadExamples();

// Two repeats of each weave, from the same curve the rake follows, as ui.js's weaveIcon draws them.
const weaveIcons = Object.fromEntries(Object.keys(WEAVE_SHAPES).map((shape) => {
  const points = [];
  for (let i = 0; i <= 96; i++) {
    const turns = (i / 96) * 2;
    const [along, across] = WEAVE_SHAPES[shape](turns - Math.floor(turns));
    points.push(`${((turns + along) * 22 + 2).toFixed(1)},${(11 - across * 8).toFixed(1)}`);
  }
  return [shape, points.join(' ')];
}));

const out = {
  note: 'Generated by scripts/fixtures.mjs. Do not edit by hand.',
  tools,
  info: INFO,
  simulators: MODELS.map((m) => ({ id: m.id, label: m.label, title: m.title })),
  palettes: BUILT_IN_PALETTES,
  examples,
  weaveIcons,
  fonts: Object.fromEntries(Object.entries(FONTS).map(([k, [label]]) => [k, label])),
};
const dir = new URL('../src/fixtures/', import.meta.url);
await mkdir(dir, { recursive: true });
await writeFile(new URL('controls.json', dir), JSON.stringify(out, null, 2) + '\n');
console.log(`${Object.keys(tools).length} tools, ${Object.values(tools).reduce((n, t) => n + t.params.length + t.choices.length, 0)} settings, ${out.simulators.length} simulators, ${out.palettes.length} palettes, ${Object.keys(examples).length} examples`);
